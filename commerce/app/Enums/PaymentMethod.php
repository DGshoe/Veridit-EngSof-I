<?php

namespace App\Enums;

/**
 * Payment providers (ADR-006). Each one is a gateway behind the Payments Adapter.
 */
enum PaymentMethod: string
{
    case Simulator = 'simulador';      // T06 "Simular confirmação / falha" — tests and demos
    case MercadoPago = 'mercadopago';  // Phase 6
    case Pix = 'pix';                  // Phase 7 — QR Code generated by Commerce, Mercado Pago as the PSP

    /** Methods that can be chosen right now in this environment. */
    public function isAvailable(): bool
    {
        return match ($this) {
            self::Simulator => (bool) config('commerce.payments.simulator.enabled'),
            self::MercadoPago => self::mercadoPagoConfigured(),
            self::Pix => self::mercadoPagoConfigured() && (bool) config('commerce.payments.mercadopago.pix_enabled'),
        };
    }

    /**
     * Name and description shown on the payment choice screen.
     *
     * @return array{name: string, description: string}
     */
    public function presentation(): array
    {
        return match ($this) {
            self::Pix => ['name' => 'PIX', 'description' => 'QR Code ou PIX copia e cola, aprovação em segundos.'],
            self::MercadoPago => ['name' => 'Mercado Pago', 'description' => 'Cartão de crédito, saldo Mercado Pago ou PIX na página do Mercado Pago.'],
            self::Simulator => ['name' => 'Simulador', 'description' => 'Ambiente de testes: nenhum valor é cobrado.'],
        };
    }

    /**
     * Who confirms payments of this method (sends the webhook). PIX is charged through
     * Mercado Pago's payments API, so its notifications arrive at the Mercado Pago webhook.
     */
    public function provider(): self
    {
        return $this === self::Pix ? self::MercadoPago : $this;
    }

    /**
     * Order payment methods a provider's webhook may settle.
     *
     * @return list<string>
     */
    public static function settledBy(self $provider): array
    {
        return array_values(array_map(
            fn (self $method) => $method->value,
            array_filter(self::cases(), fn (self $method) => $method->provider() === $provider),
        ));
    }

    private static function mercadoPagoConfigured(): bool
    {
        return filled(config('commerce.payments.mercadopago.access_token'))
            && filled(config('commerce.payments.mercadopago.webhook_secret'))
            && filled(config('commerce.payments.mercadopago.notification_url'));
    }

    /** @return list<string> */
    public static function availableValues(): array
    {
        return array_values(array_map(
            fn (self $method) => $method->value,
            array_filter(self::cases(), fn (self $method) => $method->isAvailable()),
        ));
    }
}
